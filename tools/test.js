// Run: npm i papaparse && node tools/test.js  (checks parsing and statistics without a browser)
global.window = {}; global.Papa = require('papaparse');
require('../assets/data.js'); require('../assets/stats.js');
const { data: D, stats: S } = window.TB;
let fail = 0; const eq = (a, b, m) => { if (JSON.stringify(a) !== JSON.stringify(b)) { fail++; console.log('FAIL', m, a, b); } };
eq(D.parseDate('October 26, 2026'), '2026-10-26', 'long date');
eq(D.parseDate('Oct 6, 2026 9:30 AM'), '2026-10-06', 'short month + time');
eq(D.parseDate('2026/10/26'), '2026-10-26', 'ymd slash');
eq(D.parseDate('10/26/2026', 'MDY'), '2026-10-26', 'mdy');
eq(D.parseDate('26/10/2026', 'MDY'), '2026-10-26', 'dmy auto');
eq(D.parseDate('05/10/2026', 'DMY'), '2026-10-05', 'dmy setting');
eq(D.parseDate('26 October 2026'), '2026-10-26', 'day month year');
eq(D.parseDate('October 26, 2026 → October 27, 2026'), '2026-10-26', 'range');
eq(D.stripUrls('10 AM Reversal (https://www.notion.so/10-AM-Reversal-abc?pvs=21)'), '10 AM Reversal', 'relation');
eq(D.list('A (https://www.notion.so/a), B (https://www.notion.so/b)'), ['A', 'B'], 'multi relation');
eq(D.num('$1,250.50'), 1250.5, 'money'); eq(D.num('($75.00)'), -75, 'negative money'); eq(D.num(''), null, 'empty');
eq(D.parseTime('9:52 PM'), 21 * 60 + 52, 'pm time');
eq(S.maxDrawdown([1, -1, -1, 2, -3, 1]), 3, 'drawdown');
const s = S.summary([{ r: 2, followed: true, plannedRR: 2 }, { r: -1, followed: true, plannedRR: 2 }, { r: 0, followed: false, plannedRR: 2 }]);
eq([s.n, s.wins, s.losses, s.breakeven, +s.expR.toFixed(4), s.pf], [3, 1, 1, 1, 0.3333, 2], 'summary');
const fs = require('fs');
const rows = D.parseCsvText(fs.readFileSync(__dirname + '/../data/sample/trades.csv', 'utf8'));
const schema = JSON.parse(fs.readFileSync(__dirname + '/../schema.json', 'utf8'));
const res = D.normalizeTrades(rows, schema);
eq(res.trades.length, rows.length, 'all sample rows valid'); eq(res.issues.length, 0, 'no issues in sample');
eq([...new Set(res.trades.map((t) => t.model))].sort(), ['10 AM Reversal', 'Liquidity Sweep + MSS + FVG', 'London-to-NY Continuation'], 'model names from relations');
const bad = D.normalizeTrades([{ ...rows[0], 'R multiple': '', ID: 'X' }, { ...rows[1], Result: 'Win', 'R multiple': '-1', ID: 'X' }], schema);
eq([bad.trades.length, bad.issues.length], [1, 3], 'validation catches missing R, inconsistent result, duplicate');
console.log(fail ? `${fail} failed` : 'All tests passed');
process.exit(fail ? 1 : 0);
